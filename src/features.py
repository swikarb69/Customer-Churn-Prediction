import pandas as pd
import numpy as np
from typing import List, Tuple
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline

from src.config import ID_COL, NUMERICAL_COLS, CATEGORICAL_COLS
from src.utils import setup_logger

logger = setup_logger(__name__)

def engineer_features(df: pd.DataFrame) -> pd.DataFrame:
    """Applies domain-specific feature engineering to the raw dataframe."""
    df = df.copy()

    # Drop ID column if present
    if ID_COL in df.columns:
        df = df.drop(columns=[ID_COL])

    # 1. Tenure in years
    if "tenure" in df.columns:
        df["tenure_years"] = df["tenure"] / 12.0

    # 2. Average monthly charges per tenure unit
    if "TotalCharges" in df.columns and "tenure" in df.columns:
        df["avg_monthly_charges"] = df["TotalCharges"] / (df["tenure"] + 1.0)

    # 3. Total active services subscribed
    service_cols = [
        "PhoneService", "MultipleLines", "OnlineSecurity", "OnlineBackup",
        "DeviceProtection", "TechSupport", "StreamingTV", "StreamingMovies"
    ]
    existing_services = [c for c in service_cols if c in df.columns]
    if existing_services:
        df["total_services_subscribed"] = (df[existing_services] == "Yes").sum(axis=1)

    # 4. Security & tech support bundle indicator
    if "OnlineSecurity" in df.columns and "TechSupport" in df.columns:
        df["has_security_bundle"] = (
            (df["OnlineSecurity"] == "Yes") & (df["TechSupport"] == "Yes")
        ).astype(int)

    # 5. Streaming TV & Movies bundle indicator
    if "StreamingTV" in df.columns and "StreamingMovies" in df.columns:
        df["has_streaming_bundle"] = (
            (df["StreamingTV"] == "Yes") & (df["StreamingMovies"] == "Yes")
        ).astype(int)

    # 6. Automatic payment method indicator
    if "PaymentMethod" in df.columns:
        df["is_automatic_payment"] = df["PaymentMethod"].apply(
            lambda x: 1 if isinstance(x, str) and "automatic" in x.lower() else 0
        )

    return df


class FeaturePreprocessor:
    """Encapsulates scikit-learn preprocessing pipeline for numerical and categorical columns."""

    def __init__(self):
        self.preprocessor = None
        self.feature_names_out = None

    def _build_pipeline(self, df: pd.DataFrame) -> ColumnTransformer:
        """Determines numerical and categorical columns and builds ColumnTransformer."""
        num_cols = df.select_dtypes(include=[np.number]).columns.tolist()
        cat_cols = df.select_dtypes(include=["object", "category"]).columns.tolist()

        num_pipeline = Pipeline([
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler())
        ])

        cat_pipeline = Pipeline([
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False))
        ])

        transformer = ColumnTransformer(
            transformers=[
                ("num", num_pipeline, num_cols),
                ("cat", cat_pipeline, cat_cols)
            ]
        )
        return transformer, num_cols, cat_cols

    def fit(self, X: pd.DataFrame) -> "FeaturePreprocessor":
        """Fits the preprocessing pipeline on training data."""
        X_engineered = engineer_features(X)
        self.preprocessor, num_cols, cat_cols = self._build_pipeline(X_engineered)
        self.preprocessor.fit(X_engineered)

        # Build clean output feature names
        num_names = num_cols
        cat_encoder = self.preprocessor.named_transformers_["cat"].named_steps["onehot"]
        cat_names = cat_encoder.get_feature_names_out(cat_cols).tolist()
        self.feature_names_out = num_names + cat_names

        logger.info(f"Preprocessor fit on {X.shape[0]} samples with {len(self.feature_names_out)} engineered features.")
        return self

    def transform(self, X: pd.DataFrame) -> np.ndarray:
        """Transforms feature dataframe into processed array."""
        if self.preprocessor is None:
            raise RuntimeError("FeaturePreprocessor must be fit before calling transform.")
        X_engineered = engineer_features(X)
        return self.preprocessor.transform(X_engineered)

    def fit_transform(self, X: pd.DataFrame) -> np.ndarray:
        """Fits on training data and returns transformed array."""
        self.fit(X)
        return self.transform(X)

    def get_feature_names_out(self) -> List[str]:
        """Returns feature names generated by column transformer."""
        if self.feature_names_out is None:
            raise RuntimeError("FeaturePreprocessor must be fit first.")
        return self.feature_names_out
